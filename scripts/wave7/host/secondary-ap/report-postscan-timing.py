#!/usr/bin/env python3
"""Measure actual common reply-free intervals, independently of packet sequence order.

Inputs are the combined scan report generated by report-client-scans.py.
Every reply epoch and scan epoch comes from the same client clock.
A reply-free window is not a proof of an empty air interface or a measured
transmit timestamp. Late replies and successful packets with reordered
sequence numbers remain in the arrival timeline.
"""
import argparse
from decimal import Decimal as D
import json
from pathlib import Path
import statistics


def longest_silence(arrivals,start,end):
    # Only use actual replies to bound an interval. Do not manufacture
    # endpoints by clipping an interval to the scan-analysis window.
    ordered=sorted(set(t for t in arrivals if start<=t<=end))
    if len(ordered)<2:
        return None
    duration,lo,hi=max((b-a,a,b) for a,b in zip(ordered,ordered[1:]))
    return {"last_reply":lo,"next_reply":hi,"seconds_without_observed_reply":duration,
            "last_reply_after_scan_end_s":lo-start,"next_reply_after_scan_end_s":hi-start,
            "arrivals_inside_analysis_window":len(ordered)}


def nominal_probe_period(test):
    # Only adjacent sequence numbers with known send estimates. Estimates
    # use receipt time minus displayed RTT and do not infer missing TX times.
    ordered=sorted(test["replies"],key=lambda r:r["seq"])
    intervals=[D(b["send_estimate"])-D(a["send_estimate"])
               for a,b in zip(ordered,ordered[1:]) if b["seq"]==a["seq"]+1]
    if not intervals:
        return None
    return {"samples":len(intervals),"median_s":statistics.median(intervals),
            "min_s":min(intervals),"max_s":max(intervals)}


def analyze(report):
    tests=report["tests"]
    by_target={t["target"]:t for t in tests}
    if len(by_target)!=len(tests) or len(tests)<2:
        raise ValueError("distinct simultaneous probe targets are required")
    periods={t["target"]:nominal_probe_period(t) for t in tests}
    all_arrivals=[D(r["received"]) for t in tests for r in t["replies"]]
    windows=[]
    for scope in report["scope_report"]["requests"]:
        if not scope.get("isolated_postscan_window") or not scope["tests"]:
            continue
        if not all(t["covered"] for t in scope["tests"]):
            continue
        if {t["target"] for t in scope["tests"]}!=set(by_target):
            raise ValueError("incomplete probe target coverage")
        scan=scope["matched_scan"]
        end=D(scan["end"])
        silence=longest_silence(all_arrivals,end,end+D(3))
        if silence is None:
            continue
        paths=[]
        for test in scope["tests"]:
            target=test["target"]
            raw=by_target[target]
            notices=[D(n["epoch"]) for c in test["missing_clusters"]
                     for n in c["observed_unanswered_notices"] if n["epoch"] is not None]
            # Outstanding notices are one-way observations by ping: a late
            # eventual reply is explicitly NOT counted as a lost packet.
            first=min(notices,default=None)
            last=max(notices,default=None)
            path_silence=longest_silence([D(r["received"]) for r in raw["replies"]],end,end+D(3))
            paths.append({"target":target,
                          "missing_sequences":[seq for c in test["missing_clusters"] for seq in c["sequences"]],
                          "first_missing_notice_after_scan_end_s":first-end if first is not None else None,
                          "last_missing_notice_after_scan_end_s":last-end if last is not None else None,
                          "last_observed_reply_before_first_missing_notice_s":
                          max((D(r["received"])-end for r in raw["replies"]
                               if end<=D(r["received"])<first),default=None) if first is not None else None,
                          "path_arrival_silence":path_silence})
        windows.append({"label":scope["label"],"scan_duration_s":D(scan["duration_s"]),
                        "frequencies_mhz":scan["frequencies_mhz"],
                        "common_arrival_silence":silence,"paths":paths})
    return {"periods":periods,"windows":windows,
            "method":"Maximum consecutive observed-reply epoch gap after scan completion across the union of all simultaneous probe replies, bounded by actual replies inside [scan_end,scan_end+3s]. Missing notices correspond only to sequences absent from final replies; no TX timestamps inferred for missing packets."}


def selftest():
    assert longest_silence([D("1.01"),D("1.1"),D("1.2"),D("2.1"),D("2.5")],D(1),D(4))["seconds_without_observed_reply"]==D(".9")
    # An early sequence that returns late breaks the apparent adjacent
    # missing-sequence gap. The union truly has no observed reply for
    # no more than 0.6s, even if one path has a 1.2s gap.
    a=[D("1.1"),D("1.2"),D("2.4"),D("2.5")]
    b=[D("1.15"),D("1.8"),D("2.45")]
    assert longest_silence(a+b,D(1),D(4))["seconds_without_observed_reply"]==D(".6")
    assert longest_silence([D("1.1")],D(1),D(4)) is None
    print("POSTSCAN_TIMING_SELFTEST_PASS")


if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("scope_report",type=Path,nargs="?")
    p.add_argument("--selftest",action="store_true")
    args=p.parse_args()
    if args.selftest:
        selftest()
    else:
        if args.scope_report is None:
            p.error("provide a combined scan report")
        print(json.dumps(analyze(json.loads(args.scope_report.read_text())),indent=2,default=str))
